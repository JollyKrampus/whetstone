/**
 * Dev-only: runs the whole theory chain on an unpacked heroes-data2 release and the current
 * curated files, then writes the tag report and (optionally) theory.json plus calibration stats.
 *
 *   node src/games/hots/theory/dev/build.ts --hdp <heroes-data2 dir> \
 *     [--report src/games/hots/theory/dev/tags-report.md] [--theory <out.json>] [--stats <out.md>]
 *
 * The hdp directory holds data/herodata_<build>.json and gamestrings/gamestrings_<build>_enus.json.
 * Not used by the site or the pipeline (the pipeline builds heroes.json itself).
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import { repoRoot } from '../../../../lib/datadir.ts';
import { TheorySchema, type GameMap, type Hero, type Theory } from '../../schema.ts';
import { checkCuratedAgainstHeroes, formatIssue, loadCurated } from '../curated.ts';
import { applyCuratedTraits, buildTheory } from '../engine.ts';
import { extractMechanics } from '../extract.ts';
import type { CuratedBundle, HeroInput } from '../types.ts';
import { heroInputsFromHeroesData, readHeroesData } from './fromHeroesData.ts';

/** maps.json-shaped records from maps.yaml (images and ranked flags are the pipeline's job). */
export function mapsFromCurated(curated: CuratedBundle): GameMap[] {
  return Object.entries(curated.maps.maps)
    .map(([id, m]) => ({
      id,
      name: m.name,
      kind: m.kind,
      ranked: m.kind === 'standard',
      rankedSource: 'curated' as const,
      image: `img/maps/${id}.webp`,
      profile: { size: m.size, lanes: m.lanes, objective: m.objective, tags: m.tags },
    }))
    .sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
}

/** Extracts mechanics and merges curated traits for every hero record (members included). */
export function heroesWithMechanics(inputs: readonly HeroInput[], curated: CuratedBundle): Hero[] {
  return applyCuratedTraits(
    inputs.map((h) => ({ ...h, mechanics: extractMechanics(h) })),
    curated,
  );
}

// ---- report ----------------------------------------------------------------------------

function evidenceLabel(e: Hero['mechanics'][number]['evidence'][number]): string {
  if (e.kind === 'curated') return `curated (${e.name})`;
  return e.kind === 'talent' ? `${e.name} (talent)` : e.name;
}

/** Markdown: every draftable hero with its tags and the ability/talent names behind them. */
export function tagsReport(heroes: readonly Hero[], build: string): string {
  const lines = [
    '# Theory tags per hero',
    '',
    `Generated by \`node src/games/hots/theory/dev/build.ts\` from heroes-data2 ${build} and the curated files.`,
    'Each tag lists its evidence: abilities first, then talents (marked), then curated traits. A tag whose only',
    'evidence is a talent (or one of several Heroic choices) counts at 0.6x in the rules. Do not edit by hand.',
    '',
  ];
  const entities = heroes.filter((h) => !h.memberOf).sort((a, b) => (a.slug < b.slug ? -1 : 1));
  for (const h of entities) {
    lines.push(`## ${h.name} (${h.role}${h.roleAlt ? ` / ${h.roleAlt}` : ''})`, '');
    for (const m of h.mechanics) {
      const onlyTalents = m.evidence.every((e) => e.kind === 'talent');
      lines.push(`- **${m.tag}**${onlyTalents ? ' *(talent only)*' : ''}: ${m.evidence.map(evidenceLabel).join(', ')}`);
    }
    lines.push('');
  }
  return lines.join('\n');
}

// ---- calibration -----------------------------------------------------------------------

export interface CalibrationStats {
  heroes: number;
  counters: number;
  synergies: number;
  mapFit: number;
  curatedCounters: number;
  curatedSynergies: number;
  /** Counter score histogram in buckets of 10 ("50-59" etc.). */
  counterHistogram: Record<string, number>;
  synergyHistogram: Record<string, number>;
  /** Heroes with the most incoming counter edges scoring >= 65. */
  mostCountered: { hero: string; strong: number; meanIncoming: number }[];
  /** Strongest counter edges. */
  topCounters: { a: string; b: string; score: number }[];
}

function histogram(scores: readonly number[]): Record<string, number> {
  const out: Record<string, number> = {};
  for (let lo = 0; lo <= 90; lo += 10) out[`${lo}-${lo + 9}`] = 0;
  for (const s of scores) {
    const lo = Math.min(90, Math.floor(s / 10) * 10);
    const key = `${lo}-${lo + 9}`;
    out[key] = (out[key] ?? 0) + 1;
  }
  return out;
}

export function calibrationStats(theory: Theory, heroes: readonly Hero[]): CalibrationStats {
  const name = new Map(heroes.map((h) => [h.id, h.name]));
  const entities = heroes.filter((h) => !h.memberOf);
  const incoming = new Map<string, number[]>();
  for (const e of theory.counters) incoming.set(e.b, [...(incoming.get(e.b) ?? []), e.score]);
  const mostCountered = entities
    .map((h) => {
      const list = incoming.get(h.id) ?? [];
      return { hero: h.name, strong: list.filter((s) => s >= 65).length, meanIncoming: list.length ? Math.round((list.reduce((x, y) => x + y, 0) / list.length) * 10) / 10 : 50 };
    })
    .sort((x, y) => y.strong - x.strong || y.meanIncoming - x.meanIncoming || (x.hero < y.hero ? -1 : 1))
    .slice(0, 10);
  const topCounters = [...theory.counters]
    .sort((x, y) => y.score - x.score || (x.a < y.a ? -1 : x.a > y.a ? 1 : x.b < y.b ? -1 : 1))
    .slice(0, 10)
    .map((e) => ({ a: name.get(e.a) ?? e.a, b: name.get(e.b) ?? e.b, score: e.score }));
  return {
    heroes: entities.length,
    counters: theory.counters.length,
    synergies: theory.synergies.length,
    mapFit: theory.mapFit.length,
    curatedCounters: theory.counters.filter((e) => e.source === 'curated').length,
    curatedSynergies: theory.synergies.filter((e) => e.source === 'curated').length,
    counterHistogram: histogram(theory.counters.map((e) => e.score)),
    synergyHistogram: histogram(theory.synergies.map((e) => e.score)),
    mostCountered,
    topCounters,
  };
}

export function statsMarkdown(s: CalibrationStats): string {
  const hist = (h: Record<string, number>) => Object.entries(h).filter(([, n]) => n > 0).map(([k, n]) => `| ${k} | ${n} |`);
  return [
    '# Theory calibration (real 2.57 roster)',
    '',
    `- Draftable heroes: ${s.heroes}`,
    `- Counter edges: ${s.counters} (${s.curatedCounters} with a curated pair)`,
    `- Synergy edges: ${s.synergies} (${s.curatedSynergies} with a curated pair)`,
    `- Map-fit entries: ${s.mapFit}`,
    '',
    '## Counter scores',
    '',
    '| Score | Edges |',
    '|---|---|',
    ...hist(s.counterHistogram),
    '',
    '## Synergy scores',
    '',
    '| Score | Edges |',
    '|---|---|',
    ...hist(s.synergyHistogram),
    '',
    '## Most countered (incoming counter edges scoring 65+)',
    '',
    '| Hero | Strong counters | Mean incoming score |',
    '|---|---|---|',
    ...s.mostCountered.map((m) => `| ${m.hero} | ${m.strong} | ${m.meanIncoming} |`),
    '',
    '## Strongest counter edges',
    '',
    '| Counter | Countered | Score |',
    '|---|---|---|',
    ...s.topCounters.map((t) => `| ${t.a} | ${t.b} | ${t.score} |`),
    '',
  ].join('\n');
}

// ---- CLI -------------------------------------------------------------------------------

function main(argv: string[]): number {
  const { values } = parseArgs({
    args: argv,
    options: {
      hdp: { type: 'string' },
      report: { type: 'string' },
      theory: { type: 'string' },
      stats: { type: 'string' },
    },
  });
  if (!values.hdp) {
    console.error('Usage: node src/games/hots/theory/dev/build.ts --hdp <heroes-data2 dir> [--report <md>] [--theory <json>] [--stats <md>]');
    return 2;
  }
  const root = repoRoot();
  const src = readHeroesData(values.hdp);
  const inputs = heroInputsFromHeroesData(src);
  const curated = loadCurated(root);
  for (const w of checkCuratedAgainstHeroes(curated, inputs)) console.warn(`warning ${formatIssue(w)}`);
  const heroes = heroesWithMechanics(inputs, curated);
  const build = fs.readdirSync(path.join(values.hdp, 'data')).find((f) => /^herodata_\d+\.json$/.test(f))?.replace(/\D/g, '') ?? 'unknown';
  const report = values.report ?? path.join(root, 'src', 'games', 'hots', 'theory', 'dev', 'tags-report.md');
  fs.writeFileSync(report, tagsReport(heroes, build));
  console.log(`wrote ${path.relative(root, report)}`);
  const theory = TheorySchema.parse(buildTheory({ heroes, maps: mapsFromCurated(curated), curated }));
  const stats = calibrationStats(theory, heroes);
  if (values.theory) {
    fs.writeFileSync(values.theory, `${JSON.stringify(theory, null, 2)}\n`);
    console.log(`wrote ${values.theory} (${(fs.statSync(values.theory).size / 1024).toFixed(0)} KiB)`);
  }
  if (values.stats) fs.writeFileSync(values.stats, statsMarkdown(stats));
  console.log(statsMarkdown(stats));
  return 0;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = main(process.argv.slice(2));
}
