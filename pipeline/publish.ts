/**
 * Publish job of data-deploy.yml: merge the per-game `data-<game>` artifacts into a checkout of
 * the `data` branch and decide whether the site needs a redeploy.
 *
 *   node pipeline/publish.ts --store .data-store --artifacts artifacts --games hots,mtga,pokemon
 *                            [--live-manifest https://jollykrampus.github.io/whetstone/data/manifest.json]
 *                            [--max-live-age-hours 48]
 *
 * Artifact layout (uploaded by the data job): data-<game>/{current/<game>/**, history/**, status.json}.
 * A game whose status is not `ok` (failed, skipped, crashed without status) keeps its last-good
 * current/<game> on the branch. status.json on the branch is updated for every listed game.
 *
 * Outputs (GITHUB_OUTPUT): changed (any game produced new data), deploy (changed, or the live
 * site serves a different dataHash or data older than --max-live-age-hours), failed (comma
 * list), summary (one line for the commit message).
 */
import { appendFileSync, copyFileSync, existsSync, mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import type { GameId, GameMeta } from '../src/core/game.ts';
import { GAME_IDS, META_FILE, STATUS_FILE, isGameId, mergeStatus, type GameStatus, type PublicManifest, type StatusFile } from './manifest.ts';
import { copyTree, listFiles, readJson, removeTree, resolveRel, writeJsonFile } from './store.ts';

export interface PublishOptions {
  store: string;
  artifacts: string;
  games: readonly GameId[];
  now?: Date;
  /** Parsed live public manifest, or null when it could not be fetched. Undefined skips the check. */
  live?: PublicManifest | null | undefined;
  maxLiveAgeHours?: number;
}

export interface PublishResult {
  status: StatusFile;
  changed: boolean;
  deploy: boolean;
  /** Why a deploy is needed even though nothing changed (empty when not). */
  deployReasons: string[];
  failed: GameId[];
  summary: string;
}

const DATA_BRANCH_README = `# Whetstone data branch

Generated by the daily \`data-deploy\` workflow; do not edit by hand.

- \`current/<game>/\`: latest good data per game (class A and A-SA only). \`_files.json\` lists every file's custody class.
- \`history/YYYY/MM/DD/<game>.json.gz\`: daily summaries (meta plus small class-A files).
- \`status.json\`: result of the last run per game.

Layout, schemas, licences and attribution rules: https://github.com/JollyKrampus/whetstone/blob/main/docs/DATA.md
Files derived from Liquipedia (custody A-SA) are CC-BY-SA 3.0. Heroes Profile (B) and Twitch/YouTube (C) data is never stored here.
`;

function missingStatus(game: GameId, previous: GameStatus | undefined, meta: GameMeta | null, now: Date): GameStatus {
  const detail = 'data job produced no status (crashed, timed out or was cancelled); last-good data kept';
  return {
    state: 'failed',
    checkedAt: now.toISOString(),
    generatedAt: meta?.generatedAt ?? previous?.generatedAt ?? null,
    dataHash: meta?.dataHash ?? previous?.dataHash ?? null,
    changed: false,
    durationMs: 0,
    files: previous?.files ?? { current: 0, private: 0 },
    sources: (meta?.sources ?? []).map((s) => (s.status === 'disabled' ? s : { ...s, status: 'stale', detail })),
    issues: [{ level: 'error', message: `${game}: ${detail}` }],
    detail,
  };
}

export function publish(o: PublishOptions): PublishResult {
  const now = o.now ?? new Date();
  const statusPath = path.join(o.store, STATUS_FILE);
  const previous = readJson<StatusFile>(statusPath);
  const updates: Partial<Record<GameId, GameStatus>> = {};

  for (const game of o.games) {
    const art = path.join(o.artifacts, `data-${game}`);
    const storeGame = path.join(o.store, 'current', game);
    let st = readJson<StatusFile>(path.join(art, STATUS_FILE))?.games?.[game];
    if (st?.state === 'ok' && !existsSync(path.join(art, 'current', game, META_FILE))) {
      st = { ...st, state: 'failed', changed: false, detail: 'artifact is missing current/<game>/meta.json; last-good data kept' };
    }
    if (!st) {
      updates[game] = missingStatus(game, previous?.games?.[game], readJson<GameMeta>(path.join(storeGame, META_FILE)), now);
      continue;
    }
    if (st.state === 'ok') {
      removeTree(storeGame);
      copyTree(path.join(art, 'current', game), storeGame);
      for (const rel of listFiles(path.join(art, 'history'))) {
        if (!rel.endsWith(`/${game}.json.gz`)) continue;
        const target = resolveRel(path.join(o.store, 'history'), rel);
        mkdirSync(path.dirname(target), { recursive: true });
        copyFileSync(resolveRel(path.join(art, 'history'), rel), target);
      }
    }
    updates[game] = st;
  }

  const status = mergeStatus(previous, updates, now.toISOString());
  writeJsonFile(statusPath, status);
  const readme = path.join(o.store, 'README.md');
  if (!existsSync(readme)) writeFileSync(readme, DATA_BRANCH_README);

  const changed = o.games.some((g) => updates[g]?.changed === true);
  const failed = o.games.filter((g) => updates[g]?.state === 'failed');
  const deployReasons: string[] = [];
  if (o.live !== undefined) {
    const maxAgeMs = (o.maxLiveAgeHours ?? 48) * 3_600_000;
    for (const game of GAME_IDS) {
      const meta = readJson<GameMeta>(path.join(o.store, 'current', game, META_FILE));
      if (!meta) continue;
      const live = o.live?.games?.[game];
      if (!live) deployReasons.push(`${game}: not on the live site`);
      else if (live.fixtures) deployReasons.push(`${game}: live site uses fixtures`);
      else if (live.dataHash !== meta.dataHash) deployReasons.push(`${game}: live dataHash differs`);
      else if (now.getTime() - Date.parse(live.generatedAt) > maxAgeMs) deployReasons.push(`${game}: live data older than ${o.maxLiveAgeHours ?? 48} h`);
    }
  }
  const summary = o.games.map((g) => `${g}=${updates[g]?.state ?? 'n/a'}${updates[g]?.changed ? '*' : ''}`).join(' ');
  return { status, changed, deploy: changed || deployReasons.length > 0, deployReasons, failed, summary };
}

async function fetchLive(url: string): Promise<PublicManifest | null> {
  try {
    const res = await fetch(url, { signal: AbortSignal.timeout(15_000), headers: { 'cache-control': 'no-cache' } });
    if (!res.ok) return null;
    return (await res.json()) as PublicManifest;
  } catch {
    return null;
  }
}

async function cli(argv: string[], env: NodeJS.ProcessEnv): Promise<number> {
  const { values } = parseArgs({
    args: argv,
    options: {
      store: { type: 'string' },
      artifacts: { type: 'string' },
      games: { type: 'string', default: GAME_IDS.join(',') },
      'live-manifest': { type: 'string' },
      'max-live-age-hours': { type: 'string', default: '48' },
    },
    strict: true,
  });
  if (!values.store || !values.artifacts) {
    console.error('Usage: node pipeline/publish.ts --store <data-branch checkout> --artifacts <dir> [--games a,b] [--live-manifest URL]');
    return 2;
  }
  const games = values.games.split(',').map((s) => s.trim()).filter(Boolean);
  const unknown = games.filter((g) => !isGameId(g));
  if (unknown.length > 0) {
    console.error(`Unknown game(s): ${unknown.join(', ')}`);
    return 2;
  }
  const result = publish({
    store: values.store,
    artifacts: values.artifacts,
    games: games as GameId[],
    live: values['live-manifest'] ? await fetchLive(values['live-manifest']) : undefined,
    maxLiveAgeHours: Number(values['max-live-age-hours']),
  });
  console.log(`[publish] ${result.summary}; changed=${result.changed} deploy=${result.deploy}`);
  for (const r of result.deployReasons) console.log(`[publish] deploy: ${r}`);
  if (env.GITHUB_OUTPUT) {
    appendFileSync(
      env.GITHUB_OUTPUT,
      [`changed=${result.changed}`, `deploy=${result.deploy}`, `failed=${result.failed.join(',')}`, `summary=${result.summary}`].join('\n') + '\n',
    );
  }
  if (env.GITHUB_STEP_SUMMARY) {
    const rows = games.map((g) => {
      const s = result.status.games[g as GameId];
      return `| ${g} | ${s?.state ?? '-'} | ${s?.changed ? 'yes' : 'no'} | ${s?.dataHash?.slice(0, 12) ?? '-'} | ${s?.detail ?? ''} |`;
    });
    appendFileSync(env.GITHUB_STEP_SUMMARY, ['### Publish', '', '| game | state | changed | dataHash | detail |', '|---|---|---|---|---|', ...rows, ''].join('\n') + '\n');
  }
  return 0;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  cli(process.argv.slice(2), process.env).then(
    (code) => {
      process.exitCode = code;
    },
    (err: unknown) => {
      console.error(err instanceof Error ? err.message : err);
      process.exitCode = 1;
    },
  );
}
